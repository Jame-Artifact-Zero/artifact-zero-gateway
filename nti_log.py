log = logging.getLogger("nti_log")

# ── CONNECTION ────────────────────────────────────────────────────────────────

def _get_conn():
    """Return a PostgreSQL connection from the canonical database module."""
    return database.db_connect()



def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


# ── SCHEMA INIT ───────────────────────────────────────────────────────────────

def init_log_tables() -> None:
    """Create the canonical NTI and RH request-log tables in PostgreSQL."""
    conn = _get_conn()

    try:
        cur = conn.cursor()

        cur.execute("""
            CREATE TABLE IF NOT EXISTS nti_checks (
                request_id TEXT PRIMARY KEY,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                account_id TEXT,
                user_id TEXT,
                user_email TEXT,
                surface TEXT,
                nti_version TEXT NOT NULL,
                score NUMERIC(5,2),
                nii_raw NUMERIC(5,4),
                band TEXT,
                signals JSONB,
                signal_count INTEGER,
                text_hash TEXT,
                char_count INTEGER,
                word_count INTEGER,
                rewrite_offered BOOLEAN DEFAULT FALSE,
                rewrite_accepted BOOLEAN DEFAULT FALSE,
                latency_ms INTEGER,
                ip TEXT,
                user_agent TEXT,
                metadata JSONB
            )
        """)

        cur.execute("""
            CREATE TABLE IF NOT EXISTS nti_overrides (
                id TEXT PRIMARY KEY,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                request_id TEXT NOT NULL REFERENCES nti_checks(request_id),
                account_id TEXT,
                user_id TEXT,
                user_email TEXT,
                score NUMERIC(5,2),
                signals JSONB,
                override_reason TEXT
            )
        """)

        cur.execute("""
            CREATE TABLE IF NOT EXISTS nti_stamps (
                id TEXT PRIMARY KEY,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                request_id TEXT NOT NULL REFERENCES nti_checks(request_id),
                account_id TEXT,
                user_id TEXT,
                score NUMERIC(5,2),
                stamp_text TEXT,
                recipient_domain TEXT
            )
        """)

        cur.execute("""
            CREATE TABLE IF NOT EXISTS nti_verify_hits (
                id TEXT PRIMARY KEY,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                request_id TEXT NOT NULL,
                lookup_ip TEXT,
                found BOOLEAN
            )
        """)

        cur.execute("""
            CREATE TABLE IF NOT EXISTS nti_spend (
                id TEXT PRIMARY KEY,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                request_id TEXT,
                account_id TEXT,
                model TEXT,
                call_type TEXT,
                input_tokens INTEGER,
                output_tokens INTEGER,
                cost_usd NUMERIC(10,6),
                markup_usd NUMERIC(10,6)
            )
        """)

        cur.execute("""
            CREATE TABLE IF NOT EXISTS rh_api_requests (
                id BIGSERIAL PRIMARY KEY,
                request_id TEXT NOT NULL,
                endpoint TEXT NOT NULL,
                status_code INTEGER NOT NULL,
                latency_ms NUMERIC(10,2),
                api_key_id TEXT,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)

        for statement in (
            "CREATE INDEX IF NOT EXISTS idx_checks_account "
            "ON nti_checks(account_id)",

            "CREATE INDEX IF NOT EXISTS idx_checks_user "
            "ON nti_checks(user_id)",

            "CREATE INDEX IF NOT EXISTS idx_checks_created "
            "ON nti_checks(created_at)",

            "CREATE INDEX IF NOT EXISTS idx_overrides_request "
            "ON nti_overrides(request_id)",

            "CREATE INDEX IF NOT EXISTS idx_stamps_request "
            "ON nti_stamps(request_id)",

            "CREATE INDEX IF NOT EXISTS idx_spend_account "
            "ON nti_spend(account_id)",

            "CREATE INDEX IF NOT EXISTS idx_rh_api_requests_created "
            "ON rh_api_requests(created_at)",

            "CREATE INDEX IF NOT EXISTS idx_rh_api_requests_key "
            "ON rh_api_requests(api_key_id)",
        ):
            cur.execute(statement)

        conn.commit()
        log.info("nti_log: PostgreSQL tables initialized")

    except Exception:
        conn.rollback()
        raise

    finally:
        conn.close()



# ── WRITE: CHECK ──────────────────────────────────────────────────────────────

def log_check(
    request_id: str,
    nti_version: str,
    score: float,
    nii_raw: float,
    signals: List[str],
    char_count: int,
    word_count: int,
    text_hash: str,
    latency_ms: int,
    surface: str = "api",
    account_id: Optional[str] = None,
    user_id: Optional[str] = None,
    user_email: Optional[str] = None,
    rewrite_offered: bool = False,
    rewrite_accepted: bool = False,
    ip: Optional[str] = None,
    user_agent: Optional[str] = None,
    metadata: Optional[Dict] = None,
) -> bool:
    """Write an NTI check event to PostgreSQL."""
    band = _score_to_band(score)
    conn = None

    try:
        conn = _get_conn()
        cur = conn.cursor()

        cur.execute("""
            INSERT INTO nti_checks (
                request_id,
                account_id,
                user_id,
                user_email,
                surface,
                nti_version,
                score,
                nii_raw,
                band,
                signals,
                signal_count,
                text_hash,
                char_count,
                word_count,
                rewrite_offered,
                rewrite_accepted,
                latency_ms,
                ip,
                user_agent,
                metadata
            )
            VALUES (
                %s, %s, %s, %s, %s,
                %s, %s, %s, %s, %s::jsonb,
                %s, %s, %s, %s, %s,
                %s, %s, %s, %s, %s::jsonb
            )
            ON CONFLICT (request_id) DO NOTHING
        """, (
            request_id,
            account_id,
            user_id,
            user_email,
            surface,
            nti_version,
            round(score, 2),
            round(nii_raw, 4),
            band,
            json.dumps(signals),
            len(signals),
            text_hash,
            char_count,
            word_count,
            rewrite_offered,
            rewrite_accepted,
            latency_ms,
            ip,
            user_agent,
            json.dumps(metadata or {}),
        ))

        conn.commit()
        return True

    except Exception as error:
        if conn is not None:
            conn.rollback()

        log.error(f"log_check failed: {error}")
        return False

    finally:
        if conn is not None:
            conn.close()



