"""
nti_log.py — The Log

Single source of truth for all NTI events across all surfaces.
Every check, score, rewrite, stamp, override, verify lookup, spend event writes here.

Tables:
    nti_checks      — every check event (the core record)
    nti_overrides   — when a user bypasses a failed check and sends anyway
    nti_stamps      — when a verified stamp is appended to an outbound email
    nti_verify_hits — when someone looks up a stamp at /verify/<request_id>
    nti_spend       — AI call costs per check (for billing and cap enforcement)

All tables share request_id as the join key.
request_id is generated by the calling surface (Outlook add-in, API, etc.)
and passed into every log call — so the full lifecycle of one email can be
reconstructed from a single ID.

Usage:
    from nti_log import log_check, log_override, log_stamp, log_spend, get_check, export_checks

Environment:
    PostgreSQL is required and is accessed through db.db_connect().
"""

import os
