# ── READ: VERIFY ──────────────────────────────────────────────────────────────

def get_check(
    request_id: str,
    lookup_ip: Optional[str] = None,
) -> Optional[Dict]:
    """
    Return the public verification record and log the lookup attempt.
    """
    conn = None

    try:
        conn = _get_conn()
        cur = conn.cursor()

        cur.execute("""
            SELECT
                request_id,
                created_at,
                nti_version,
                score,
                band,
                signals,
                signal_count
            FROM nti_checks
            WHERE request_id = %s
        """, (request_id,))

        row = cur.fetchone()
        found = row is not None
        result = None

        if found:
            raw_signals = row[5]

            if isinstance(raw_signals, str):
                parsed_signals = json.loads(raw_signals)
            else:
                parsed_signals = raw_signals or []

            result = {
                "request_id": row[0],
                "checked_at": row[1],
                "nti_version": row[2],
                "score": (
                    float(row[3])
                    if row[3] is not None
                    else None
                ),
                "band": row[4],
                "signals": parsed_signals,
                "signal_count": row[6],
                "verified": True,
            }

        cur.execute("""
            INSERT INTO nti_verify_hits (
                id,
                request_id,
                lookup_ip,
                found
            )
            VALUES (%s, %s, %s, %s)
        """, (
            str(uuid.uuid4()),
            request_id,
            lookup_ip,
            found,
        ))

        conn.commit()
        return result

    except Exception as error:
        if conn is not None:
            conn.rollback()

        log.error(f"get_check failed: {error}")
        return None

    finally:
        if conn is not None:
            conn.close()



# ── READ: REPORTING ───────────────────────────────────────────────────────────

def get_account_stats(
    account_id: str,
    days: int = 30,
) -> Dict[str, Any]:
    """Return PostgreSQL-backed NTI account statistics."""
    conn = None

    try:
        period_days = max(
            1,
            min(int(days), 3650),
        )

        conn = _get_conn()
        cur = conn.cursor()

        cur.execute("""
            SELECT
                COUNT(*) AS total_checks,
                ROUND(AVG(score)::numeric, 1) AS avg_score,
                COUNT(*) FILTER (
                    WHERE band = 'SOLID'
                ) AS solid_count,
                COUNT(*) FILTER (
                    WHERE band = 'REVIEW'
                ) AS review_count,
                COUNT(*) FILTER (
                    WHERE band = 'HIGH_RISK'
                ) AS high_risk_count,
                COUNT(*) FILTER (
                    WHERE rewrite_accepted = TRUE
                ) AS rewrites_accepted,
                COUNT(*) FILTER (
                    WHERE rewrite_offered = TRUE
                ) AS rewrites_offered
            FROM nti_checks
            WHERE account_id = %s
              AND created_at >= (
                  NOW() - (%s * INTERVAL '1 day')
              )
        """, (
            account_id,
            period_days,
        ))

        stats = cur.fetchone()

        cur.execute("""
            SELECT COUNT(*)
            FROM nti_overrides
            WHERE account_id = %s
              AND created_at >= (
                  NOW() - (%s * INTERVAL '1 day')
              )
        """, (
            account_id,
            period_days,
        ))

        override_count = cur.fetchone()[0]

        cur.execute("""
            SELECT ROUND(
                SUM(cost_usd + markup_usd)::numeric,
                4
            )
            FROM nti_spend
            WHERE account_id = %s
              AND created_at >= (
                  NOW() - (%s * INTERVAL '1 day')
              )
        """, (
            account_id,
            period_days,
        ))

        spend = cur.fetchone()[0] or 0.0

        rewrite_rate = 0.0

        if stats[6] and stats[6] > 0:
            rewrite_rate = round(
                (stats[5] or 0)
                / stats[6]
                * 100,
                1,
            )

        return {
            "account_id": account_id,
            "period_days": period_days,
            "total_checks": stats[0] or 0,
            "avg_score": (
                float(stats[1])
                if stats[1] is not None
                else 0.0
            ),
            "band_distribution": {
                "solid": stats[2] or 0,
                "review": stats[3] or 0,
                "high_risk": stats[4] or 0,
            },
            "override_count": override_count or 0,
            "rewrite_acceptance_rate_pct": rewrite_rate,
            "spend_usd": float(spend),
        }

    except Exception as error:
        log.error(f"get_account_stats failed: {error}")
        return {}

    finally:
        if conn is not None:
            conn.close()



def export_checks_csv(
    account_id: str,
    days: int = 30,
) -> List[Dict]:
    """Return PostgreSQL NTI check records for CSV export."""
    conn = None

    try:
        period_days = max(
            1,
            min(int(days), 3650),
        )

        conn = _get_conn()
        cur = conn.cursor()

        cur.execute("""
            SELECT
                request_id,
                created_at,
                user_email,
                surface,
                score,
                band,
                signal_count,
                signals,
                rewrite_offered,
                rewrite_accepted,
                latency_ms
            FROM nti_checks
            WHERE account_id = %s
              AND created_at >= (
                  NOW() - (%s * INTERVAL '1 day')
              )
            ORDER BY created_at DESC
        """, (
            account_id,
            period_days,
        ))

        columns = [
            description[0]
            for description in cur.description
        ]

        return [
            dict(zip(columns, row))
            for row in cur.fetchall()
        ]

    except Exception as error:
        log.error(f"export_checks_csv failed: {error}")
        return []

    finally:
        if conn is not None:
            conn.close()



# ── HELPERS ───────────────────────────────────────────────────────────────────

def _score_to_band(score: float) -> str:
    if score >= 80:
        return "SOLID"
    elif score >= 60:
        return "REVIEW"
    return "HIGH_RISK"


def make_request_id() -> str:
    """Generate a request ID. Surfaces can use this or supply their own."""
    return str(uuid.uuid4())


def hash_text(text: str) -> str:
    """SHA256 of input text. Stored in log — never the text itself."""
    import hashlib
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


